"""
Generate embeddings for DSA problems.

Owner: Bhooshan Deshpande (Member B)

Two modes:

  1. Write the seed file (default). Embeds every problem in the database and
     overwrites db/04b_B_embeddings.sql with one INSERT per problem. Commit
     that file so a fresh clone gets working semantic search with no model
     download and no API key.

       python flask_backend/scripts/generate_embeddings_sql.py \
           --database-url postgresql://postgres:<pw>@localhost:5432/academiaos

  2. Backfill a live database (--apply). Embeds only problems whose embedding
     is Missing or Stale (see v_embedding_status) and writes them through
     fn_upsert_embedding.

       python flask_backend/scripts/generate_embeddings_sql.py --apply \
           --database-url postgresql://postgres:<pw>@localhost:5432/academiaos

Connect as the database owner (e.g. postgres) so row-level security does not
hide other users' problems.

Requires: pip install sentence-transformers psycopg2-binary
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import psycopg2

MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"
MODEL_LABEL = "all-MiniLM-L6-v2"   # value stored in dsa_embeddings.model
DIMENSIONS = 384

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "db" / "04b_B_embeddings.sql"

HEADER = """\
-- =============================================================================
-- 04b_B_embeddings.sql
-- Owner: Bhooshan Deshpande (Member B)
-- GENERATED by flask_backend/scripts/generate_embeddings_sql.py. Do not edit.
-- Model: {model} ({dims} dimensions), embeddings normalised to unit length.
-- Text embedded per problem: fn_embedding_text(title, intuition_notes),
-- i.e. title + newline + notes. source_hash = md5 of that text.
-- Rows are matched by (user_id, platform, title), not by problem_id, so this
-- file does not depend on the order ids were generated in.
-- =============================================================================

"""


def load_model():
    from sentence_transformers import SentenceTransformer  # heavy import, load lazily
    return SentenceTransformer(MODEL_NAME)


def to_pgvector(values) -> str:
    """Format a vector as pgvector's text input: '[0.1,0.2,...]'."""
    return "[" + ",".join(f"{float(v):.6f}" for v in values) + "]"


def embed(model, texts: list[str]):
    vectors = model.encode(texts, normalize_embeddings=True, batch_size=32,
                           show_progress_bar=False)
    for v in vectors:
        if len(v) != DIMENSIONS:
            raise SystemExit(f"Model returned {len(v)} dimensions, expected {DIMENSIONS}")
    return vectors


def write_seed_file(conn, model, out_path: Path) -> int:
    with conn.cursor() as cur:
        cur.execute("""
            SELECT p.user_id::text, p.platform, p.title,
                   fn_embedding_text(p.title, p.intuition_notes) AS text,
                   md5(fn_embedding_text(p.title, p.intuition_notes)) AS hash
            FROM dsa_problems p
            ORDER BY p.user_id, p.platform, p.title
        """)
        rows = cur.fetchall()

        if not rows:
            raise SystemExit("No problems found. Build and seed the database first.")

        vectors = embed(model, [r[3] for r in rows])

        statements = []
        for (user_id, platform, title, _text, hash_), vec in zip(rows, vectors):
            stmt = cur.mogrify(
                "INSERT INTO dsa_embeddings (problem_id, embedding, model, source_hash)\n"
                "SELECT p.problem_id, %s::vector, %s, %s\n"
                "FROM dsa_problems p\n"
                "WHERE p.user_id = %s AND p.platform = %s AND p.title = %s;\n",
                (to_pgvector(vec), MODEL_LABEL, hash_, user_id, platform, title),
            ).decode()
            statements.append(stmt)

    out_path.write_text(HEADER.format(model=MODEL_LABEL, dims=DIMENSIONS)
                        + "\n".join(statements), encoding="utf-8")
    return len(statements)


def apply_backfill(conn, model) -> dict[str, int]:
    with conn.cursor() as cur:
        cur.execute("""
            SELECT problem_id, text_to_embed
            FROM v_embedding_status
            WHERE embedding_state IN ('Missing', 'Stale')
            ORDER BY problem_id
        """)
        rows = cur.fetchall()
        counts = {"inserted": 0, "updated": 0, "unchanged": 0}
        if not rows:
            return counts

        vectors = embed(model, [r[1] for r in rows])
        for (problem_id, _text), vec in zip(rows, vectors):
            cur.execute("SELECT fn_upsert_embedding(%s, %s::vector, %s)",
                        (problem_id, to_pgvector(vec), MODEL_LABEL))
            counts[cur.fetchone()[0]] += 1
    conn.commit()
    return counts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--database-url", default=os.environ.get("ADMIN_DATABASE_URL"),
                        help="Owner connection string (default: $ADMIN_DATABASE_URL)")
    parser.add_argument("--apply", action="store_true",
                        help="Embed Missing/Stale problems directly into the database")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT,
                        help=f"Seed file to write (default: {DEFAULT_OUT})")
    args = parser.parse_args()

    if not args.database_url:
        parser.error("pass --database-url or set ADMIN_DATABASE_URL")

    model = load_model()
    conn = psycopg2.connect(args.database_url)
    try:
        if args.apply:
            counts = apply_backfill(conn, model)
            print(f"Backfill done: {counts}")
        else:
            n = write_seed_file(conn, model, args.out)
            print(f"Wrote {n} embeddings to {args.out}")
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
